/** Mainline version → its per-minor page path (relative to repo root). */
export function pageForVersion(version) {
  const parsed = parseVersion(version);
  return `${CHANGELOG_DIR}/v${parsed.major}-${parsed.minor}.md`;
}

/** The `## X.Y.Z` heading slugs a page already exposes (reuses check-links' slug). */
function versionHeadingSlugs(pageContent) {
  const slugs = new Set();
  for (const match of pageContent.matchAll(/^##\s+(.+?)\s*$/gmu)) {
    slugs.add(slug(match[1]));
  }
  return slugs;
}

/** Does `pageContent` already document `## {version}`? */
export function hasVersionSection(pageContent, version) {
  return versionHeadingSlugs(pageContent).has(slug(version));
}

// ───────────────────────────────────────────────────────── rendering ──

/** Clean a commit subject for a published .md doc: Linear refs (SDK-xxx) are not
 *  allowed in docs, so strip them. */
function cleanSubjectForDoc(subject) {
  return subject
    .replace(/\[SDK-\d+\](?:\[SDK-\d+\])*/gu, "")
    .replace(/\((?:SDK-\d+)\)/gu, "")
    .replace(/\bSDK-\d+\b/gu, "")
    .replace(/\s{2,}/gu, " ")
    .replace(/\s+([.,;:])/gu, "$1")
    .trim();
}

/** Render a parsed bullet as a doc bullet: `- **scope:** subject ([#PR](url))`. */
export function renderBullet(bullet) {
  const subject = cleanSubjectForDoc(bullet.subject);
  let out = bullet.scope ? `- **${bullet.scope}:** ${subject}` : `- ${subject}`;
  if (bullet.prNumber) {
    const url = bullet.prUrl || `https://github.com/zama-ai/sdk/issues/${bullet.prNumber}`;
    out += ` ([#${bullet.prNumber}](${url}))`;
  }
  return out;
}

function renderSectionBody(sections, headingLevel) {
  const hashes = "#".repeat(headingLevel);
  const parts = [];
  for (const section of sections) {
    parts.push(`${hashes} ${section.type}`);
    if (section.lowTrust) {
      parts.push(
        "<!-- low-trust: squashed breaking-changes block; verify against CHANGELOG.md before writing prose -->",
      );
    }
    parts.push("");
    for (const bullet of section.bullets) {
      parts.push(renderBullet(bullet));
    }
    parts.push("");
  }
  return parts.join("\n").trimEnd();
}

/** A `## {version}` STUB section: released date, TODO marker, raw bullets by type. */
export function renderStubSection(release) {
  return [
    `## ${release.version}`,
    "",
    `_Released ${release.date}._`,
    "",
    TODO_MARKER,
    "",
    renderSectionBody(release.sections, 3),
    "",
  ]
    .join("\n")
    .trimEnd();
}

/** The `{minor}.x` page for a brand-new minor line, with its first section(s). */
export function renderMinorPage(version, sectionsMarkdown, { description } = {}) {
  const parsed = parseVersion(version);
  const title = `${parsed.major}.${parsed.minor}.x`;
  return [
    "---",
    `title: ${title}`,
    `description: ${description ?? `Release notes for the ${title} line.`}`,
    "---",
    "",
    `# ${title}`,
    "",
    `This page covers the \`${title}\` line.`,
    "",
    sectionsMarkdown.join("\n\n").trimEnd(),
    "",
  ].join("\n");
}

/** The machine-owned Beta raw-material block: every beta build since the last
 *  stable release, grouped by section, for the skill to rewrite. */
export function renderRawMaterialBlock(betaReleases, lastMainlineVersion) {
  const parts = [
    RAW_START,
    "",
    "## Release notes (raw material)",
    "",
    TODO_MARKER,
    "",
    `_Skeleton of the beta builds since \`${lastMainlineVersion}\`. The \`sdk-changelog\` skill rewrites these into the plain-language notes above; this block is regenerated by \`pnpm docs:changelog\` and dropped when the release is promoted._`,
    "",
  ];
  for (const release of betaReleases) {
    parts.push(`### ${release.version} — ${release.date}`, "");
    if (release.sections.length === 0) {
      parts.push("_No release-note-worthy changes._", "");
      continue;
    }
    parts.push(renderSectionBody(release.sections, 4), "");
  }
  parts.push(RAW_END);
  return parts.join("\n");
}

/** The beta versions a page's raw-material block currently documents, or null if
 *  the block is absent. Used for SEMANTIC idempotency (version-set match), so the
 *  block is only regenerated when the set of beta builds actually changes. */
export function betaBlockVersions(betaContent) {
  const block = extractBetween(betaContent, RAW_START, RAW_END);
  if (block === null) {
    return null;
  }
  return [...block.matchAll(/^###\s+(\d+\.\d+\.\d+-beta\.\d+)\b/gmu)].map((match) => match[1]);
}

// ────────────────────────────────────────────────── nav / page wiring ──

/** Insert a `{minor}.x` section into an existing page, keeping sections newest-first. */
export function insertSection(pageContent, version, sectionMarkdown) {
  const target = parseVersion(version);
  const lines = pageContent.split("\n");
  const block = `${sectionMarkdown.trimEnd()}\n`;

  for (let i = 0; i < lines.length; i++) {
    if (!lines[i].startsWith("## ")) {
      continue;
    }
    const existing = parseVersion(lines[i].slice(3).trim());
    if (existing && compareVersions(existing, target) < 0) {
      lines.splice(i, 0, ...block.split("\n"), "");
      return lines.join("\n");
    }
  }
  // No lower section found — this is the oldest; append at the end.
  return `${pageContent.replace(/\s*$/u, "")}\n\n${block}`;
}

/** True if SUMMARY already links the page for `major.minor`. */
export function summaryHasMinor(summaryContent, major, minor) {
  return summaryContent.includes(`changelog/v${major}-${minor}.md`);
}

/** Add a `{minor}.x` child under the active-major node in the SUMMARY Changelog
 *  block (2-space indent — corpus parseSummary derives nav depth from it), as the
 *  newest (first) child. No-op if already present. */
export function insertMinorIntoSummary(summaryContent, version) {
  const { major, minor } = parseVersion(version);
  if (summaryHasMinor(summaryContent, major, minor)) {
    return summaryContent;
  }
  const lines = summaryContent.split("\n");
  const suffix = `](changelog/v${major}.md)`;
  const anchor = lines.findIndex(
    (line) => line.startsWith("- [") && line.trimEnd().endsWith(suffix),
  );
  if (anchor === -1) {
    return summaryContent;
  }
  lines.splice(anchor + 1, 0, `  - [${major}.${minor}.x](changelog/v${major}-${minor}.md)`);
  return lines.join("\n");
}

/** Add a `{minor}.x` bullet to the top of the major-index page's version list.
 *  No-op if already present. */
export function insertMinorIntoIndex(indexContent, version) {
  const { major, minor } = parseVersion(version);
  if (indexContent.includes(`(v${major}-${minor}.md)`)) {
    return indexContent;
  }
  const title = `${major}.${minor}.x`;
  const bullet = `- [**${title}**](v${major}-${minor}.md) — Release notes for the ${title} line.`;
  const lines = indexContent.split("\n");
  const heading = lines.findIndex((line) => /^##\s+Versions\s*$/u.test(line));
  if (heading === -1) {
    return `${indexContent.replace(/\s*$/u, "")}\n\n${bullet}\n`;
  }
  // Skip the blank line after the heading, insert as the first bullet.
  let insertAt = heading + 1;
  while (insertAt < lines.length && lines[insertAt].trim() === "") {
    insertAt++;
  }
  lines.splice(insertAt, 0, bullet);
  return lines.join("\n");
}

// ─────────────────────────────────────────────────── beta page prose ──

/** Return the substring between `start` and `end` markers (exclusive), or null. */
function extractBetween(content, start, end) {
  const from = content.indexOf(start);
  if (from === -1) {
    return null;
  }
  const to = content.indexOf(end, from + start.length);
  if (to === -1) {
    return null;
  }
  return content.slice(from + start.length, to);
}

function stripFrontmatter(content) {
  return content.replace(/^---\n[\s\S]*?\n---\n?/u, "");
}

/** Drop the leading `# Title` H1 (the Beta page's own title) — the version page
 *  supplies its own H1 and `## {version}` header, so it must not carry over. */
function stripPageTitle(body) {
  return body.replace(/^\s*#\s+.*(?:\n|$)/u, "");
}

/** Remove the leading "Unreleased" warning banner (matched by content, not style —
 *  editorial prose legitimately contains other warning/info hints that must stay). */
function stripUnreleasedBanner(body) {
  return body.replace(
    /\{%\s*hint\s+style="warning"\s*%\}[\s\S]*?Unreleased[\s\S]*?\{%\s*endhint\s*%\}\s*/u,
    "",
  );
}

/** Remove the machine-owned raw-material block (with its markers). */
function stripRawMaterial(body) {
  const from = body.indexOf(RAW_START);
  if (from === -1) {
    return body;
  }
  const to = body.indexOf(RAW_END, from);
  if (to === -1) {
    return body.slice(0, from);
  }
  return body.slice(0, from) + body.slice(to + RAW_END.length);
}

/** Lower every markdown heading by `by` levels (fence-aware: `#` inside fenced code
 *  blocks is left alone). The Beta page authors release topics as `##` under its
 *  `# Beta` title, but a version page nests topics as `###` under `## {version}`,
 *  so promotion demotes the moved prose by one level to keep it inside the section. */
export function demoteHeadings(markdown, by = 1) {
  let fence = null;
  return markdown
    .split("\n")
    .map((line) => {
      const fenceMatch = /^\s*(```+|~~~+)/u.exec(line);
      if (fenceMatch) {
        const marker = fenceMatch[1][0];
        if (fence === null) {
          fence = marker;
        } else if (marker === fence) {
          fence = null;
        }
        return line;
      }
      if (fence !== null) {
        return line;
      }
      const headingMatch = /^(#{1,6})(\s)/u.exec(line);
      if (headingMatch) {
        const level = Math.min(6, headingMatch[1].length + by);
        return "#".repeat(level) + line.slice(headingMatch[1].length);
      }
      return line;
    })
    .join("\n");
}

/** The editorial prose on the Beta page — everything a release promotion should
 *  carry into the version page: frontmatter, the Unreleased banner, and the
 *  raw-material block are stripped; the rest (including any other hints) is kept.
 *  Headings are demoted one level so the page's `##` topics nest as `###` under the
 *  version's `##` heading. */
export function extractBetaProse(betaContent) {
  const body = stripRawMaterial(
    stripUnreleasedBanner(stripPageTitle(stripFrontmatter(betaContent))),
  ).trim();
  return demoteHeadings(body, 1);
}

/** Does the Beta page carry genuine staged content (vs. the empty reset template)?
 *  Semantic check: after stripping frontmatter/banner/raw-material/comments and the
 *  known placeholder, is there any substance left? Robust to oxfmt reflow. */
export function betaHasSubstance(betaContent) {
  const remainder = stripHtmlComments(extractBetaProse(betaContent))
    .split("\n")
    .filter((line) => normalizeWhitespace(line) !== normalizeWhitespace(BETA_EMPTY_PLACEHOLDER))
    .join("\n")
    .trim();
  return remainder.length > 0;
}

/** Strip HTML comments, repeating until stable so a nested or adjacent construct
 *  like `<!--<!-- -->-->` can't leave a live `<!--` behind after a single pass. */
function stripHtmlComments(text) {
  let previous;
  let current = text;
  do {
    previous = current;
    current = current.replace(/<!--[\s\S]*?-->/gu, "");
  } while (current !== previous);
  return current;
}

function normalizeWhitespace(text) {
  return text.replace(/\s+/gu, " ").trim();
}

/** The Beta page reset to its empty template (post-promotion state). */
export function emptyBetaTemplate() {
  return [
    "---",
    "title: Beta",
    "description: Unreleased changes on the prerelease (beta) line — not yet in a stable release.",
    "---",
    "",
    "# Beta",
    "",
    '{% hint style="warning" %}',
    "**Unreleased.** The changes on this page are on the prerelease (`beta`) line and are **not yet available in a stable release**. They ship with the next stable release, at which point this page is retitled to that version and folded into the version list above. Treat everything here as a preview — details may still change before release.",
    "{% endhint %}",
    "",
    BETA_EMPTY_PLACEHOLDER,
    "",
  ].join("\n");
}

/** Splice the raw-material block into the Beta page (replacing an existing block,
 *  or appending one). */
function withRawMaterialBlock(betaContent, block) {
  const from = betaContent.indexOf(RAW_START);
  if (from === -1) {
    return `${betaContent.replace(/\s*$/u, "")}\n\n${block}\n`;
  }
  const to = betaContent.indexOf(RAW_END, from);
  const end = to === -1 ? betaContent.length : to + RAW_END.length;
  return betaContent.slice(0, from) + block + betaContent.slice(end);
}

// ────────────────────────────────────────────────── in-memory edit set ──

/** Accumulates file edits in memory so callers can compute everything first and
 *  flush at the end — giving failure isolation (a mid-way throw leaves the tree
 *  untouched) and a clean dry-run mode. Tracks the original bytes so `flush()`
 *  reports (and writes) only files whose content actually changed. */
class EditSet {
  constructor(root) {
    this.root = root;
    this.files = new Map(); // absPath -> { original, content }
  }

  #entry(relPath) {
    const abs = join(this.root, relPath);
    if (!this.files.has(abs)) {
      const original = existsSync(abs) ? readFileSync(abs, "utf8") : null;
      this.files.set(abs, { original, content: original });
    }
    return this.files.get(abs);
  }

  read(relPath) {
    return this.#entry(relPath).content;
  }

  exists(relPath) {
    return this.#entry(relPath).content !== null;
  }

  write(relPath, content) {
    this.#entry(relPath).content = content;
  }

  /** Absolute paths whose content differs from disk (would be / were written). */
  changedPaths() {
    const changed = [];
    for (const [abs, { original, content }] of this.files) {
      if (content !== null && content !== original) {
        changed.push(abs);
      }
    }
    return changed;
  }

  flush() {
    const changed = this.changedPaths();
    for (const abs of changed) {
      writeFileSync(abs, this.files.get(abs).content);
    }
    return changed;
  }
}

// ───────────────────────────────────────────────────────────── modes ──

/**
 * Scaffold missing mainline `## {version}` sections and refresh the Beta raw
 * material. Idempotent + no-op-safe: only genuinely missing sections/pages/nav
 * entries and a stale beta version-set trigger writes.
 *
 * @param {{ root?: string, version?: string, dryRun?: boolean }} [opts]
 * @returns {{ changed: string[], missing: string[] }} absolute changed paths + a
 *   human-readable list of what was (or would be) scaffolded.
 */
export function scaffoldChangelog({ root = process.cwd(), version, dryRun = false } = {}) {
  const edits = new EditSet(root);
  const releases = parseChangelog(readChangelog(edits, root));
  const missing = [];

  let mainline = mainlineReleasesForActiveMajor(releases);
  if (version) {
    mainline = mainline.filter((rel) => rel.version === version);
  }
  // Oldest-first so newest ends up on top when each is inserted newest-first.
  for (const release of mainline.toReversed()) {
    const pagePath = pageForVersion(release.version);
    if (!edits.exists(pagePath)) {
      edits.write(pagePath, renderMinorPage(release.version, [renderStubSection(release)]));
      edits.write(SUMMARY_PATH, insertMinorIntoSummary(edits.read(SUMMARY_PATH), release.version));
      edits.write(
        MAJOR_INDEX_PATH,
        insertMinorIntoIndex(edits.read(MAJOR_INDEX_PATH), release.version),
      );
      missing.push(`new page ${pagePath} + ## ${release.version}`);
      continue;
    }
    const pageContent = edits.read(pagePath);
    if (!hasVersionSection(pageContent, release.version)) {
      edits.write(
        pagePath,
        insertSection(pageContent, release.version, renderStubSection(release)),
      );
      missing.push(`## ${release.version} → ${pagePath}`);
    }
  }

  // Beta raw material — only in full (un-scoped) scaffold mode.
  if (!version) {
    const betas = betaReleasesSinceLastMainline(releases);
    const lastMainline = newestMainline(releases);
    if (betas.length > 0 && lastMainline) {
      const betaContent = edits.read(BETA_PAGE_PATH);
      const targetVersions = betas.map((rel) => rel.version);
      const current = betaBlockVersions(betaContent);
      const upToDate = current !== null && arraysEqual(current, targetVersions);
      if (!upToDate) {
        const block = renderRawMaterialBlock(betas, lastMainline.version);
        edits.write(BETA_PAGE_PATH, withRawMaterialBlock(betaContent, block));
        missing.push(`Beta raw material (${targetVersions.join(", ")})`);
      }
    }
  }

  const changed = dryRun ? edits.changedPaths() : edits.flush();
  return { changed, missing };
}

/**
 * Promote the Beta page into the shipped version's page/section, reset Beta to
 * the empty template, and wire nav for a new minor line. Version is auto-derived
 * from the newest mainline entry in CHANGELOG.md; `opts.version` overrides.
 *
 * Does NOT run oxfmt/llm:build — the caller (docs:retarget main) owns that
 * ordering and folds the returned `changed` paths into its own format+build pass.
 *
 * Own state detection (retarget's "idempotent" is output-stable, not "does
 * nothing"): the version page already having `## {version}` is the workhorse
 * no-op guard (makes `retarget main` twice a zero-diff); an already-empty Beta
 * page is the secondary "nothing staged" guard. All file contents are computed in
 * memory and flushed only if every step succeeds (failure isolation).
 *
 * @param {{ root?: string, version?: string, dryRun?: boolean }} [opts]
 * @returns {{ changed: string[], version: string|null, promoted: boolean, reason?: string,
 *   warning?: string }}
 *   `changed` = absolute paths (version page, reset beta.md, and SUMMARY.md when a
 *   new minor page is created). `warning` is set (no-op path only) when the state
 *   looks like a stale CHANGELOG.md — see the "already promoted" guard.
 */
export function promoteChangelog({ root = process.cwd(), version, dryRun = false } = {}) {
  const edits = new EditSet(root);
  const releases = parseChangelog(readChangelog(edits, root));

  const target = version ?? newestMainline(releases)?.version ?? null;
  if (!target) {
    return { changed: [], version: null, promoted: false, reason: "no mainline release found" };
  }

  const pagePath = pageForVersion(target);
  const targetBasename = basename(pagePath);
  const pageContent = edits.exists(pagePath) ? edits.read(pagePath) : null;

  // Workhorse guard: already promoted. Normally that means retarget ran twice — a
  // true no-op. But if the Beta page STILL carries staged content while the newest
  // mainline entry is already on its page, CHANGELOG.md is very likely STALE: the
  // release commit (`chore(release): X.Y.Z [skip ci]`) that adds the NEW `## [X.Y.Z]`
  // hasn't been pulled, so `target` derived to the PRIOR, already-promoted version.
  // That would silently ship a release with no version page and no beta reset — and
  // a MISSING page is not a broken link, so nothing downstream (incl. check-links)
  // catches it. Warn loudly, but stay a no-op (exit 0 preserved): retarget runs at
  // merge time, so failing here would block the merge.
  if (pageContent !== null && hasVersionSection(pageContent, target)) {
    const result = { changed: [], version: target, promoted: false, reason: "already promoted" };
    if (betaHasSubstance(edits.read(BETA_PAGE_PATH))) {
      result.warning =
        `⚠ Beta page has unreleased content but the newest mainline entry (${target}) is ` +
        "already promoted — CHANGELOG.md may be stale; did you pull the release commit " +
        "before running docs:retarget main?";
    }
    return result;
  }

  // Secondary guard: nothing staged on the Beta page.
  const betaContent = edits.read(BETA_PAGE_PATH);
  if (!betaHasSubstance(betaContent)) {
    return { changed: [], version: target, promoted: false, reason: "beta page is empty" };
  }

  const date = releases.find((rel) => rel.version === target && !rel.isPrerelease)?.date;
  // Repoint self-referential beta anchors in the prose BEFORE it lands on the version
  // page — the inbound sweep below can't fix them (the version page isn't on disk yet).
  const prose = repointSelfAnchors(extractBetaProse(betaContent), targetBasename);
  const section = [`## ${target}`, "", `_Released ${date ?? "unreleased"}._`, "", prose].join("\n");

  if (pageContent === null) {
    edits.write(pagePath, renderMinorPage(target, [section]));
    edits.write(SUMMARY_PATH, insertMinorIntoSummary(edits.read(SUMMARY_PATH), target));
    edits.write(MAJOR_INDEX_PATH, insertMinorIntoIndex(edits.read(MAJOR_INDEX_PATH), target));
  } else {
    edits.write(pagePath, insertSection(pageContent, target, section));
  }
  edits.write(BETA_PAGE_PATH, emptyBetaTemplate());

  // Repoint inbound anchors before the moved sections vanish from the Beta page.
  repointBetaAnchors(edits, root, extractHeadingSlugs(prose), targetBasename);

  const changed = dryRun ? edits.changedPaths() : edits.flush();
  return { changed, version: target, promoted: true };
}

function arraysEqual(a, b) {
  return a.length === b.length && a.every((value, index) => value === b[index]);
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
}

/** Every `.md` page under the GitBook source tree (relative to root). */
function docPagesRelative(root) {
  const srcDir = join(root, "docs/gitbook/src");
  if (!existsSync(srcDir)) {
    return [];
  }
  return readdirSync(srcDir, { recursive: true })
    .filter((name) => typeof name === "string" && name.endsWith(".md"))
    .map((name) => join("docs/gitbook/src", name));
}

/**
 * Repoint inbound anchor links from the Beta page to the version page the content
 * moved to. Promotion moves a section (e.g. `## FHE runtime…`) out of `beta.md`
 * and resets the page, so any `](…beta.md#that-slug)` elsewhere would dangle and
 * fail check-links at the release merge. Only the file part of the link changes —
 * `beta.md` → `vX-Y.md` (both sit in `changelog/`, so relative prefixes stay
 * valid) — and only for slugs that actually moved. Edits go through the shared set
 * so they land in the returned `changed[]` (and get oxfmt'd + rebuilt by retarget).
 */
function repointBetaAnchors(edits, root, movedSlugs, targetBasename) {
  if (movedSlugs.size === 0) {
    return;
  }
  // Path-boundary the prefix: an optional group that must END in `/` (a directory
  // separator) or be absent (start-of-path, right after `](`). Otherwise a sibling
  // like `mybeta.md#slug` would spuriously match (`my` as the prefix).
  const patterns = [...movedSlugs].map((movedSlug) =>
    RE2JS.compile(`\\]\\(([^)#]*\\/)?beta\\.md#(${escapeRegExp(movedSlug)})\\)`),
  );
  for (const relPath of docPagesRelative(root)) {
    const content = edits.read(relPath);
    if (content === null || !content.includes("beta.md#")) {
      continue;
    }
    let updated = content;
    for (const pattern of patterns) {
      updated = pattern.matcher(updated).replaceAll((_match, prefix, anchor) => {
        return `](${prefix ?? ""}${targetBasename}#${anchor})`;
      });
    }
    if (updated !== content) {
      edits.write(relPath, updated);
    }
  }
}

/**
 * Rewrite SELF-referential beta anchors INSIDE the moved prose. A link like
 * `](beta.md#other-section)` (or `](./beta.md#…)`) within the Beta prose points at
 * another section on the SAME page; once that prose moves to the version page and
 * beta.md resets, it would dangle. The inbound sweep (`repointBetaAnchors`) can't
 * fix it — the version page isn't on disk when that sweep reads the tree — so rewrite
 * it here, swapping only the file part to the version page basename (both live in
 * `changelog/`, so a relative link stays valid). Path-boundary anchored (the `./`
 * prefix or start-of-path) so a sibling like `mybeta.md` is left alone.
 */
function repointSelfAnchors(prose, targetBasename) {
  return prose.replace(
    /\]\((\.\/)?beta\.md#([^)]+)\)/gu,
    (_match, prefix, anchor) => `](${prefix ?? ""}${targetBasename}#${anchor})`,
  );
}

// ───────────────────────────────────────────────────── orchestration ──

function relativeTo(root, absPath) {
  return absPath.startsWith(`${root}/`) ? absPath.slice(root.length + 1) : absPath;
}

/** Format changed files, rebuild the corpus, then run the link check — in that
 *  order (oxfmt BEFORE llm:build). Invoked only on the changed path; returns an
 *  exit code. */
function runBuildPipeline(root, changed) {
  const binDir = join(root, "node_modules/.bin");
  const oxfmt = join(binDir, "oxfmt");
  const oxfmtCmd = existsSync(oxfmt) ? oxfmt : "oxfmt";

  const fmt = spawnSync(oxfmtCmd, changed, { cwd: root, stdio: "inherit" });
  if (fmt.status !== 0) {
    return fmt.status ?? 1;
  }

  // build-llms shells a bare `oxfmt`, so it needs node_modules/.bin on PATH.
  console.log("\nRebuilding the LLM corpus...");
  const build = spawnSync("node", [join(scriptDir, "../llm/build-llms.mjs")], {
    cwd: root,
    stdio: "inherit",
    env: { ...process.env, PATH: `${binDir}:${process.env.PATH ?? ""}` },
  });
  if (build.status !== 0) {
    return build.status ?? 1;
  }

  const failures = checkTree();
  if (failures.length > 0) {
    console.error(`\n✖ ${failures.length} broken internal doc link(s):\n`);
    for (const failure of failures) {
      console.error(`  ${failure}`);
    }
    return 1;
  }
  console.log("✓ Internal links check out.");
  return 0;
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const versionIndex = args.indexOf("--version");
  const version = versionIndex !== -1 ? args[versionIndex + 1] : undefined;
  if (versionIndex !== -1 && !version) {
    console.error("Usage: pnpm docs:changelog [--check] [--version X.Y.Z]");
    process.exit(1);
  }

  const root = process.cwd();
  const { changed, missing } = scaffoldChangelog({ root, version, dryRun: check });

  if (check) {
    if (missing.length === 0) {
      console.log("✓ Changelog is up to date — nothing to scaffold.");
    } else {
      console.log(`Would scaffold ${missing.length} item(s):`);
      for (const item of missing) {
        console.log(`  - ${item}`);
      }
    }
    return; // dry-run always exits 0 (no-op-safe: reporting is never a failure).
  }

  if (changed.length === 0) {
    console.log("✓ Changelog is up to date — nothing to scaffold.");
    return; // no-op-safe: write nothing, run no oxfmt/build/check-links.
  }

  console.log(`Scaffolded ${changed.length} file(s):`);
  for (const item of missing) {
    console.log(`  - ${item}`);
  }
  for (const abs of changed) {
    console.log(`  · ${relativeTo(root, abs)}`);
  }

  const code = runBuildPipeline(root, changed);
  if (code !== 0) {
    process.exit(code);
  }
  console.log("\n✓ Changelog scaffolded. Commit the changes (sources + regenerated corpus).");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
