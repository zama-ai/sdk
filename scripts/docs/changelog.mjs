// Scaffold the human-readable GitBook changelog from semantic-release's CHANGELOG.md,
// and promote the Beta page into a shipped version page.
//
//   pnpm docs:changelog                 scaffold missing sections + refresh Beta raw material
//   pnpm docs:changelog --check         dry-run: report what's missing, write nothing
//   pnpm docs:changelog --version X.Y.Z scope scaffolding to one version (escape hatch)
//
// Two surfaces: CHANGELOG.md (repo root, semantic-release-generated, commit-level) and
// docs/gitbook/src/changelog/*.md (hand-written per-minor pages + a Beta page for the
// unreleased tip). This does the MECHANICAL half: parse CHANGELOG.md, scaffold missing
// `## {version}` sections as STUBs (raw bullets + TODO, never prose), add `{minor}.x`
// pages + nav for a new minor line, and refresh the machine-owned "raw material" block on
// the Beta page. The `sdk-changelog` skill writes the prose; promotion (beta → version at
// release) is exported as promoteChangelog(), driven by docs:retarget main.
//
// Two invariants (mirroring retarget.mjs):
//   - NO-OP-SAFE: exit 0 with no writes when nothing changed (runs at merge time; a spurious
//     failure blocks the merge — so no oxfmt/llm:build/check-links on the no-op path either).
//   - IDEMPOTENT: presence detected SEMANTICALLY (heading/file/nav exists), never by byte-diffing
//     generated markdown (oxfmt reflows it). oxfmt runs BEFORE llm:build, always (the #538/3.3.0 gate).

import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { RE2JS } from "re2js";
import { checkTree, extractHeadingSlugs, slug } from "./check-links.mjs";

const scriptDir = dirname(fileURLToPath(import.meta.url));

/** The active, per-minor-paginated major line. Frozen majors (1.x/2.x) are single
 *  pages and are never touched by this script. */
export const ACTIVE_MAJOR = 3;

export const CHANGELOG_PATH = "CHANGELOG.md";
export const CHANGELOG_DIR = "docs/gitbook/src/changelog";
export const SUMMARY_PATH = "docs/gitbook/src/SUMMARY.md";
export const BETA_PAGE_PATH = `${CHANGELOG_DIR}/beta.md`;
export const MAJOR_INDEX_PATH = `${CHANGELOG_DIR}/v${ACTIVE_MAJOR}.md`;

export const TODO_MARKER = "<!-- TODO: rewrite as plain-language notes -->";
export const RAW_START =
  "<!-- docs:changelog raw-material:start — regenerated by pnpm docs:changelog, dropped on promotion -->";
export const RAW_END = "<!-- docs:changelog raw-material:end -->";

/** The reset state of the Beta page after promotion — a stable template so the
 *  "already reset" check is semantic (see betaHasSubstance), not byte-exact. */
const BETA_EMPTY_PLACEHOLDER =
  "_Nothing is staged for the next release yet. As beta builds land, run `pnpm docs:changelog` to refresh this page._";

// ───────────────────────────────────────────────────────────── parsing ──

/** `## [X.Y.Z](compare-url) (YYYY-MM-DD)` — the semantic-release version heading. */
const VERSION_HEADING_RE = /^## \[([^\]]+)\]\(([^)]+)\)\s+\((\d{4}-\d{2}-\d{2})\)\s*$/;
const SECTION_HEADING_RE = /^###\s+(.+?)\s*$/;
const BULLET_RE = /^-\s+(.+)$/;

export function isBetaVersion(version) {
  return /-beta\.\d+$/.test(version);
}

/** `3.4.0-beta.6` → { major, minor, patch, prerelease }. Returns null if unparseable. */
export function parseVersion(version) {
  const match = /^(\d+)\.(\d+)\.(\d+)(?:-(.+))?$/.exec(version);
  if (!match) {
    return null;
  }
  return {
    major: Number(match[1]),
    minor: Number(match[2]),
    patch: Number(match[3]),
    prerelease: match[4] ?? null,
  };
}

/** Newest-first ordering: mainline sorts AFTER its own prereleases (3.4.0 > 3.4.0-beta.6). */
export function compareVersions(a, b) {
  const va = typeof a === "string" ? parseVersion(a) : a;
  const vb = typeof b === "string" ? parseVersion(b) : b;
  for (const key of ["major", "minor", "patch"]) {
    if (va[key] !== vb[key]) {
      return va[key] - vb[key];
    }
  }
  // Equal core version: a release with no prerelease outranks one with a prerelease.
  if (!va.prerelease && vb.prerelease) {
    return 1;
  }
  if (va.prerelease && !vb.prerelease) {
    return -1;
  }
  if (va.prerelease && vb.prerelease) {
    return va.prerelease.localeCompare(vb.prerelease, undefined, { numeric: true });
  }
  return 0;
}

/** Strip the trailing `([#PR](url)) ([hash](url))` metadata and `, closes …` tail
 *  from a bullet's text, leaving the human subject. */
function stripBulletMeta(text) {
  return text
    .replace(/,\s*closes\s+.*$/iu, "")
    .replace(/(?:\s*\(\[[^\]]*\]\([^)]*\)\))+\s*$/u, "")
    .trim();
}

/** Parse one `- …` bullet into its parts. Tolerant of both empty `([h]())` and
 *  full-URL `([h](https://…))` hash links, and of missing scope/PR. */
export function parseBullet(line) {
  const raw = BULLET_RE.exec(line)?.[1] ?? line.replace(/^-\s+/, "");
  let text = raw;

  let scope = null;
  const scopeMatch = /^\*\*([^:*]+):\*\*\s*/u.exec(text);
  if (scopeMatch) {
    scope = scopeMatch[1].trim();
    text = text.slice(scopeMatch[0].length);
  }

  let prNumber = null;
  let prUrl = null;
  const prMatch = /\(\[#(\d+)\]\(([^)]*)\)\)/u.exec(text);
  if (prMatch) {
    prNumber = prMatch[1];
    prUrl = prMatch[2] || null;
  }

  let hashLink = null;
  const hashMatch = /\(\[([0-9a-f]{6,40})\]\(([^)]*)\)\)/u.exec(text);
  if (hashMatch) {
    hashLink = { hash: hashMatch[1], url: hashMatch[2] || null };
  }

  const linearRefs = [...raw.matchAll(/SDK-\d+/gu)].map((match) => match[0]);

  return { scope, subject: stripBulletMeta(text), prNumber, prUrl, hashLink, linearRefs, raw };
}

/**
 * Parse CHANGELOG.md into a newest-first list of releases. Each release has typed
 * H3 sections; each section a list of parsed bullets. `### ⚠ BREAKING CHANGES`
 * blocks carry squash noise (Co-Authored-By lines, stray `*`/`-` bullets) — they
 * are marked `lowTrust` so callers know not to render them verbatim. The parser
 * never throws on that noise: non-`- ` lines are simply ignored.
 */
export function parseChangelog(text) {
  const releases = [];
  let release = null;
  let section = null;

  for (const line of text.split("\n")) {
    const versionMatch = VERSION_HEADING_RE.exec(line);
    if (versionMatch) {
      const [, version, compareUrl, date] = versionMatch;
      const parsed = parseVersion(version);
      release = {
        version,
        compareUrl,
        date,
        isBeta: isBetaVersion(version),
        // Any suffix (`-alpha.N` or `-beta.N`) is a prerelease; only bare `X.Y.Z` is a
        // shipped mainline. `isBeta` alone must NOT be read as "is mainline" — with the
        // alpha channel added, an `-alpha.N` entry has isBeta=false but is not mainline.
        isPrerelease: (parsed?.prerelease ?? null) !== null,
        major: parsed?.major ?? null,
        minor: parsed?.minor ?? null,
        patch: parsed?.patch ?? null,
        sections: [],
      };
      releases.push(release);
      section = null;
      continue;
    }
    if (!release) {
      continue;
    }
    const sectionMatch = SECTION_HEADING_RE.exec(line);
    if (sectionMatch) {
      const type = sectionMatch[1];
      section = { type, lowTrust: /breaking changes/iu.test(type), bullets: [] };
      release.sections.push(section);
      continue;
    }
    if (BULLET_RE.test(line)) {
      if (!section) {
        section = { type: "Changes", lowTrust: false, bullets: [] };
        release.sections.push(section);
      }
      section.bullets.push(parseBullet(line));
    }
  }

  // Drop empty sections (a heading with no parsed bullets contributes nothing).
  for (const rel of releases) {
    rel.sections = rel.sections.filter((sec) => sec.bullets.length > 0);
  }
  return releases;
}

// ─────────────────────────────────────────────────── release selection ──

export function newestMainline(releases) {
  return releases.find((rel) => !rel.isPrerelease) ?? null;
}

/** Read CHANGELOG.md from the edit set, failing with a descriptive error (rather
 *  than a raw `TypeError` from `parseChangelog(null)`) when it is missing/unreadable.
 *  Retarget already catches a promotion throw and aborts before any write; this just
 *  makes the scaffold path's message actionable. */
function readChangelog(edits, root) {
  const text = edits.read(CHANGELOG_PATH);
  if (text === null) {
    throw new Error(`CHANGELOG.md not found/unreadable at ${join(root, CHANGELOG_PATH)}`);
  }
  return text;
}

/** Mainline releases on the active major, newest-first. */
export function mainlineReleasesForActiveMajor(releases) {
  return releases.filter((rel) => !rel.isPrerelease && rel.major === ACTIVE_MAJOR);
}

/** Beta builds newer than the newest mainline release (the unreleased tip),
 *  newest-first. CHANGELOG is newest-first, so these are the prerelease entries above
 *  the first mainline heading. `alpha` builds are off the changelog, so they're skipped
 *  from the collection — but an `-alpha.N` entry is NOT the mainline boundary (only a
 *  suffix-less version is), so break on `!isPrerelease`, not `!isBeta`. */
export function betaReleasesSinceLastMainline(releases) {
  const out = [];
  for (const rel of releases) {
    if (!rel.isPrerelease) {
      break;
    }
    if (rel.isBeta) {
      out.push(rel);
    }
  }
  return out;
}

